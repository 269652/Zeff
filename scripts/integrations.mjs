#!/usr/bin/env node
/**
 * npm run integrations — which integrations are mounted under integrations/<name>/ (see
 * src/lib/integrations/types.ts), written to src/lib/integrations/mounted-{meta,server,client}.ts.
 * Those files are generated and not committed; without any mount they are empty and Zeff has no
 * integration plugins (no Chrono, no Punch). Run by dev, build, test, typecheck and the deploy.
 *
 *   node scripts/integrations.mjs            write the files
 *   node scripts/integrations.mjs --check    exit 1 when they are out of date
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "integrations");
const out = path.join(root, "src", "lib", "integrations");

/** The mounted integrations: a folder of integrations/ with at least one of the entry modules. */
export function mounted(base = dir) {
  if (!fs.existsSync(base)) return [];
  return fs
    .readdirSync(base, { withFileTypes: true })
    .filter((e) => !e.name.startsWith(".") && fs.statSync(path.join(base, e.name)).isDirectory()) // (a link counts: a checkout may be linked in)
    .map((e) => ({ name: e.name, has: Object.fromEntries(["meta", "server", "client"].map((k) => [k, fs.existsSync(path.join(base, e.name, `${k}.ts`))])) }))
    .filter((m) => m.has.meta || m.has.server || m.has.client)
    .sort((a, b) => a.name.localeCompare(b.name));
}

const HEADER = "// Generated by scripts/integrations.mjs (npm run integrations) — which integrations are mounted. Not committed.\n";

/** The three generated modules' text, for the mounts found. */
export function render(list = mounted()) {
  const files = {};
  for (const [kind, type, field] of [["meta", "MountedMeta", "meta"], ["server", "MountedServer", "server"], ["client", "MountedClient", "client"]]) {
    const have = list.filter((m) => m.has[kind]);
    const imports = have.map((m, i) => `import { ${field} as m${i} } from "../../../integrations/${m.name}/${kind}";`).join("\n");
    const rows = have.map((m, i) => `  { dir: "integrations/${m.name}", ${field}: m${i} },`).join("\n");
    files[`mounted-${kind}.ts`] = `${HEADER}import type { ${type} } from "./types";\n${imports ? `${imports}\n` : ""}\nexport const MOUNTED_${kind.toUpperCase()}: ${type}[] = [${rows ? `\n${rows}\n` : ""}];\n`;
  }
  return files;
}

export function write() {
  const files = render();
  fs.mkdirSync(out, { recursive: true });
  let changed = 0;
  for (const [name, text] of Object.entries(files)) {
    const file = path.join(out, name);
    if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === text) continue;
    fs.writeFileSync(file, text);
    changed++;
  }
  return { changed, mounts: mounted().map((m) => m.name) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const stale = Object.entries(render()).filter(([name, text]) => !fs.existsSync(path.join(out, name)) || fs.readFileSync(path.join(out, name), "utf8") !== text);
    if (stale.length) {
      console.error(`integrations: ${stale.map(([n]) => n).join(", ")} out of date — run npm run integrations`);
      process.exit(1);
    }
  } else {
    const r = write();
    console.log(`integrations: ${r.mounts.length ? r.mounts.join(", ") : "none mounted"}${r.changed ? ` (${r.changed} file(s) written)` : ""}`);
  }
}
