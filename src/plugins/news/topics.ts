const bing = (q: string, lang: "de" | "en") => `https://www.bing.com/news/search?q=${encodeURIComponent(q)}&format=rss&mkt=${lang === "de" ? "de-DE" : "en-US"}`;

/** The topic packs as catalog feeds (category "Topics"). */
export function topicFeeds(topics: Topic[] = TOPICS): CatalogFeed[] {
  return topics.flatMap((t): CatalogFeed[] => [
    { category: "Topics", name: `Google News · ${t.en}`, url: topicFeedUrl(t.en, "en", 7), lang: "en" },
    { category: "Topics", name: `Google News · ${t.de}`, url: topicFeedUrl(t.de, "de", 7), lang: "de" },
    { category: "Topics", name: `Bing News · ${t.en}`, url: bing(t.en, "en"), lang: "en" },
    { category: "Topics", name: `Bing News · ${t.de}`, url: bing(t.de, "de"), lang: "de" },
    ...(t.medium ? [{ category: "Topics", name: `Medium · ${t.en}`, url: `https://medium.com/feed/tag/${t.medium}`, lang: "en" }] : []),
  ]);
}
