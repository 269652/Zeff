import fs from "node:fs";
import path from "node:path";

/** What scripts/plugins-index.mts writes (and tests/plugin-index.test.ts compares): the generated plugin indexes. Node only. */
const scan = (root: string) => fs.readdirSync(root, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort();
const v = (d: string) => "p_" + d.replace(/[^a-z0-9]/g, "_");
export const pluginsDir = () => path.join(process.cwd(), "src", "plugins");

/** plugins/index.generated.ts — the manifests (client-safe: data only). */
export function renderManifests(root = pluginsDir()): string {
  const ids = scan(root).filter((d) => fs.existsSync(path.join(root, d, "plugin.ts")));
  return [
    "// GENERATED by `npm run plugins:index` from src/plugins/*/plugin.ts — do not edit.",
    ...ids.map((d) => `import ${v(d)} from "./${d}/plugin";`),
    "",
    "/** Every built-in plugin's manifest (unsorted; plugins/catalog.ts orders them). */",
    `export const BUILTIN_MANIFESTS = [${ids.map(v).join(", ")}] as const;`,
    "",
  ].join("\n");
}

/** plugins/server.generated.ts — each plugin's server.ts, imported for what it registers (server only). */
export function renderServer(root = pluginsDir()): string {
  const ids = scan(root).filter((d) => fs.existsSync(path.join(root, d, "server.ts")));
  return ["// GENERATED by `npm run plugins:index` from src/plugins/*/server.ts — do not edit.", ...ids.map((d) => `import "./${d}/server";`), ""].join("\n");
}

