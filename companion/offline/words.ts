export const tr = (key: string, vars: Record<string, string | number> = {}): string => (W[key]?.[DE ? 1 : 0] ?? key).replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));

export const fmtTime = (iso: string) => new Date(iso).toLocaleTimeString(undefined, { hour: "2-digit", minute: "2-digit" });
export const fmtDay = (day: string) => new Date(`${day.slice(0, 10)}T12:00:00`).toLocaleDateString(undefined, { weekday: "short", day: "numeric", month: "short" });
export const today = () => new Date().toLocaleDateString("sv-SE");
